"""PlatformIO pre-script: compile the web UI (data/) into the firmware.

Each file in data/ is gzipped and written as a byte array into a generated
header (web_assets.h, in the build directory) that src/web_server.cpp serves
with Content-Encoding: gzip. The UI then ships inside the signed firmware
image: one OTA update carries both, they can't get out of step, and no
separate file-system upload is needed.

The header is rewritten only when its content changes, so an unchanged UI
doesn't trigger a recompile. gzip runs with mtime=0, so the output (and the
firmware image) is reproducible.
"""

import gzip
from pathlib import Path

Import("env")  # noqa: F821 (injected by PlatformIO / SCons)

DATA_DIR = Path(env.subst("$PROJECT_DIR")) / "data"  # noqa: F821
OUT_DIR = Path(env.subst("$BUILD_DIR")) / "generated"  # noqa: F821
HEADER = OUT_DIR / "web_assets.h"
CONTENT_TYPES = {
    ".html": "text/html",
    ".js": "text/javascript",
    ".css": "text/css",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
}
BYTES_PER_LINE = 16


def asset_files() -> list:
    files = sorted(p for p in DATA_DIR.iterdir() if p.is_file() and not p.name.startswith("."))
    unknown = [p.name for p in files if p.suffix not in CONTENT_TYPES]
    if unknown:
        print(f"Error: web_assets.py has no content type for {', '.join(unknown)}")
        env.Exit(1)  # noqa: F821
    if not any(p.name == "index.html" for p in files):
        print(f"Error: {DATA_DIR}/index.html is missing")
        env.Exit(1)  # noqa: F821
    return files


def c_array(name: str, data: bytes) -> str:
    rows = []
    for i in range(0, len(data), BYTES_PER_LINE):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + BYTES_PER_LINE]) + ",")
    return f"static const uint8_t {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def render(files: list) -> str:
    arrays, entries = [], []
    for i, path in enumerate(files):
        gz = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
        name = f"kAsset{i}"
        arrays.append(f"// /{path.name}: {path.stat().st_size} bytes, {len(gz)} gzipped\n" + c_array(name, gz))
        entries.append(f'    {{"/{path.name}", "{CONTENT_TYPES[path.suffix]}", {name}, sizeof({name})}},')
    return (
        "// web_assets.h — GENERATED by tools/web_assets.py from data/. Do not edit.\n"
        "#pragma once\n\n#include <stddef.h>\n#include <stdint.h>\n\n"
        "namespace fogger {\nnamespace web {\n\n"
        "struct Asset {\n  const char* path;         // URL path, e.g. \"/app.js\"\n"
        "  const char* contentType;\n  const uint8_t* gzip;      // gzip-compressed body\n"
        "  size_t gzipLen;\n};\n\n"
        + "\n".join(arrays)
        + "\nstatic const Asset kAssets[] = {\n" + "\n".join(entries) + "\n};\n"
        + "static constexpr size_t kAssetCount = sizeof(kAssets) / sizeof(kAssets[0]);\n\n"
        "}  // namespace web\n}  // namespace fogger\n"
    )


files = asset_files()
text = render(files)
OUT_DIR.mkdir(parents=True, exist_ok=True)
if not HEADER.is_file() or HEADER.read_text() != text:
    HEADER.write_text(text)
env.Append(CPPPATH=[str(OUT_DIR)])  # noqa: F821
total = sum(p.stat().st_size for p in files)
print(f"Web UI: {len(files)} files, {total} bytes, built into the firmware")
